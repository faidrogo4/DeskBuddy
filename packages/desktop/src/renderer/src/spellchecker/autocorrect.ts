const isAllCaps = (word: string): boolean => {
  const letters = word.replace(/\P{L}/gu, '')
  return letters.length > 1 && letters === letters.toUpperCase()
}

/**
 * The correction for a just-finished English `word`, or null to leave it.
 *
 * @param boundary The character that finished the word.
 * @param isKnownWord Words the user accepted (dictionary or ignore list) are
 *   never corrected.
 */
export const getAutoCorrection = (
  word: string,
  boundary: string,
  isKnownWord: (word: string) => boolean
): string | null => {
  // ALL CAPS is far more often an acronym ("ADN", "NTO") than a typo.
  if (isAllCaps(word) || isKnownWord(word)) return null

  const lower = word.toLowerCase()
  // A lone "i" before a period is far more often "i.e." or a roman numeral.
  if (lower === 'i') return word === 'i' && boundary !== '.' ? 'I' : null

  const replacement = RULES[lower]
  if (!replacement) return null
  // "Teh" -> "The"; corrections capitalised by nature ("I've") stay so.
  return word[0] === lower[0] ? replacement : replacement[0].toUpperCase() + replacement.slice(1)
}
